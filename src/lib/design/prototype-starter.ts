export function applyPrototypeStarter(files: ProjectFiles): ProjectFiles {
  const packageJson = JSON.parse(files["package.json"] ?? "{}") as Record<
    string,
    unknown
  > & { dependencies?: Record<string, string> };
  packageJson.dependencies = {
    ...(packageJson.dependencies ?? {}),
    "react-router-dom": "^7.18.3",
  };
  packageJson.openBuilder = {
    profile: PROTOTYPE_PROJECT_PROFILE,
    schemaVersion: 1,
  };
  const tsconfig = JSON.parse(files["tsconfig.json"] ?? "{}") as Record<
    string,
    unknown
  >;
  tsconfig.include = ["**/*.ts", "**/*.tsx"];
  tsconfig.exclude = ["vite.config.ts", "node_modules", "dist"];

  return {
    ...files,
    "package.json": JSON.stringify(packageJson, null, 2) + "\n",
    "tsconfig.json": JSON.stringify(tsconfig, null, 2) + "\n",
    "App.tsx": PROTOTYPE_APP,
    "prototype/PrototypeData.tsx": PROTOTYPE_DATA,
    "prototype/PrototypeHome.tsx": PROTOTYPE_HOME,
    "styles.css": PROTOTYPE_STYLES,
    "README.md": PROTOTYPE_README,
  };
}

export function isPrototypeProject(files: ProjectFiles): boolean {
  try {
    const packageJson = JSON.parse(files["package.json"] ?? "{}") as {
      openBuilder?: { profile?: unknown; schemaVersion?: unknown };
    };
    return (
      packageJson.openBuilder?.profile === PROTOTYPE_PROJECT_PROFILE &&
      packageJson.openBuilder.schemaVersion === 1
    );
  } catch {
    return false;
  }
}
